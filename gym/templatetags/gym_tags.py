@register.simple_tag
def icon(name, size=20, cls=""):
    body = ICONS.get(name, "")
    return mark_safe(
        f'<svg class="icon {cls}" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{body}</svg>'
    )


@register.filter
def money(value, currency=None):
    """12500.00 -> '12 500 DA'"""
    try:
        v = Decimal(value or 0)
    except (InvalidOperation, TypeError, ValueError):
        return value
    txt = f"{v:,.2f}".replace(",", "\u202f")
    if txt.endswith(".00"):
        txt = txt[:-3]
    if currency is None:
        from ..models import GymSettings
        currency = GymSettings.get().currency
    out = f"{txt}\u00a0{currency}" if currency else txt
    return "\u2066" + out + "\u2069"  # isolate: Arabic pages keep "12 500 DA" order


STATUS = {
    "active": ("ok", "Active"),
    "expiring": ("warn", "Expiring soon"),
    "expired": ("bad", "Expired"),
    "frozen": ("info", "Paused"),
    "upcoming": ("info", "Upcoming"),
    "none": ("muted", "No subscription"),
    "cancelled": ("muted", "Cancelled"),
}


@register.simple_tag
def status_badge(status):
    cls, label = STATUS.get(status, ("muted", status))
    return format_html('<span class="badge badge-{}">{}</span>', cls, _(label))


@register.filter
def status_label(status):
    return _(STATUS.get(status, ("", status))[1])


@register.simple_tag
def wa_link(member, template_text, gym_name, date="", debt=""):
    from urllib.parse import quote
    msg = template_text.format_map(_SafeDict(name=member.first_name, gym=gym_name, date=date, debt=debt))
    return f"https://wa.me/{member.whatsapp_phone}?text={quote(msg)}"


class _SafeDict(dict):
    def __missing__(self, key):
        return "{" + key + "}"


@register.simple_tag(takes_context=True)
def qs(context, **kwargs):
    """Keep current GET params, change some: {% qs page=2 %}"""
    q = context["request"].GET.copy()
    for k, v in kwargs.items():
        if v in (None, ""):
            q.pop(k, None)
        else:
            q[k] = v
    return "?" + q.urlencode()


@register.filter
def percent(part, whole):
    try:
        return round(float(part) * 100 / float(whole)) if float(whole) else 0
    except (TypeError, ValueError):
        return 0
